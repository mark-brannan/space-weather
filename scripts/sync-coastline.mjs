/**
 * Copies the coastline geography this webapp draws into public/, the same
 * way scripts/sync-icon.mjs copies the icon: a real file has to ship, and
 * the browser loads the page unbundled, so it cannot reach node_modules or
 * data/.
 *
 * `coast-wright` turns GeoJSON into rings and draws them -- verbatim copies
 * into public/vendor/coast-wright/, since these files import each other by
 * relative path. The geography is Natural Earth's coastline GeoJSON,
 * vendored unmodified in data/ so install, build and test need no network;
 * it is checked against the pinned digest below before it is wrapped as an
 * ES module (`export default {...}`), because public/geo.js needs to
 * `import` it statically and JSON module imports still aren't safe to assume
 * across the browsers this plugin runs in.
 */
import { createHash } from 'node:crypto'
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

export const COASTLINE_VERSION = 'v5.1.2'
export const COASTLINE_URL = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${COASTLINE_VERSION}/geojson/ne_50m_coastline.geojson`
export const COASTLINE_SHA256 =
  '271f1c4c1908312bac6b29d158ea1356544beafc129f260005300913aa5ea283'

const source = fileURLToPath(
  new URL('../data/ne_50m_coastline.geojson', import.meta.url)
)
const publicDir = fileURLToPath(new URL('../public', import.meta.url))
const vendorDir = fileURLToPath(
  new URL('../public/vendor/coast-wright', import.meta.url)
)

const geojson = readFileSync(source)
const digest = createHash('sha256').update(geojson).digest('hex')
if (digest !== COASTLINE_SHA256) {
  console.error(
    `data/ne_50m_coastline.geojson is not Natural Earth ${COASTLINE_VERSION}:\n` +
      `  expected sha256 ${COASTLINE_SHA256}\n` +
      `  found    sha256 ${digest}\n` +
      `Restore it from ${COASTLINE_URL}`
  )
  process.exit(1)
}

mkdirSync(vendorDir, { recursive: true })
for (const file of ['index.js', 'decode.js', 'geojson.js', 'limn.js']) {
  copyFileSync(
    fileURLToPath(
      new URL(`../node_modules/coast-wright/lib/${file}`, import.meta.url)
    ),
    new URL(`${file}`, `file://${vendorDir}/`)
  )
}

writeFileSync(
  new URL('coastline.js', `file://${publicDir}/`),
  `// Generated by scripts/sync-coastline.mjs -- do not edit by hand.\n` +
    `// Natural Earth ${COASTLINE_VERSION} 50m coastline, public domain,\n` +
    `// unmodified: ${COASTLINE_URL}\n` +
    `// sha256 ${COASTLINE_SHA256}\n` +
    `// public/geo.js draws it through "coast-wright".\n` +
    `export default ${geojson.toString('utf8').trim()}\n`
)
