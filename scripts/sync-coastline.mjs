/**
 * Copies the coastline geography this webapp draws into public/, the same
 * way scripts/sync-icon.mjs copies the icon: a real file has to ship, and
 * the source of truth for both now lives outside this repo.
 *
 * `coast-wright` decodes and draws portolani -- verbatim copies into
 * public/vendor/coast-wright/, since these files import each other by
 * relative path and the browser loads them unbundled. `coastlines` ships the
 * ready-made 110m coastline profile as JSON; it is wrapped as an ES module
 * (`export default {...}`) rather than copied raw, because public/geo.js
 * needs to `import` it statically and JSON module imports still aren't safe
 * to assume across the browsers this plugin runs in.
 *
 * Neither package is bundled -- both are devDependencies, resolved from
 * node_modules at build time, exactly like the icon.
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const publicDir = fileURLToPath(new URL('../public', import.meta.url))
const vendorDir = fileURLToPath(
  new URL('../public/vendor/coast-wright', import.meta.url)
)
mkdirSync(vendorDir, { recursive: true })

for (const file of ['index.js', 'decode.js', 'limn.js']) {
  copyFileSync(
    fileURLToPath(
      new URL(`../node_modules/coast-wright/lib/${file}`, import.meta.url)
    ),
    new URL(`${file}`, `file://${vendorDir}/`)
  )
}

const coastlineJson = readFileSync(
  fileURLToPath(
    new URL(
      '../node_modules/coastlines/data/coastline-110m.json',
      import.meta.url
    )
  ),
  'utf8'
)

writeFileSync(
  new URL('coastline.js', `file://${publicDir}/`),
  `// Generated by scripts/sync-coastline.mjs -- do not edit by hand.\n` +
    `// The "coastline-110m" profile from the "coastlines" npm package\n` +
    `// (Natural Earth 110m coastline, public domain, simplified and\n` +
    `// delta-encoded by "portolani"). public/geo.js decodes and draws it\n` +
    `// through "coast-wright".\n` +
    `export default ${coastlineJson.trim()}\n`
)
